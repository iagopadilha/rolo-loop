//! Free inventory of the code of a folder: sizes, entry points and giant files (no AI, no network).
//!
//! `harness inventory <folder> [--json] [--giant-lines N] [--giant-kb N] [--changed a,b] [--root R] [--name N] [--out F] [--no-write]`.
//! Default file: `<root>/.specs/project/loop/internal/inventory/<name>.json`, written atomically, and only when `<root>/.specs` exists.

use crate::classify_structure::is_skipped;
use crate::scale::is_code;
use pycompat::json::py_json_dumps_indent;
use pycompat::{nt_abspath, nt_dirname, Re};
use serde_json::{json, Map, Value};
use std::path::{Path, PathBuf};
use std::sync::LazyLock;

pub const DEFAULT_GIANT_LINES: i64 = 1500;
pub const DEFAULT_GIANT_KB: i64 = 200;
pub const ROOT_NAME: &str = "_root";
/// Where the inventories live, relative to the repository root (forward slashes).
pub const INVENTORY_RELATIVE_DIR: &str = ".specs/project/loop/internal/inventory";
const LOCK_FILES: [&str; 8] = ["package-lock.json", "yarn.lock", "pnpm-lock.yaml", "composer.lock", "poetry.lock", "gemfile.lock", "cargo.lock", "go.sum"];
const HEADER_BYTES: usize = 1024;
const HINT_SCAN_BYTES: usize = 4 * 1024 * 1024;
const HINT_LIMIT: usize = 5;
const SHALLOW_ENTRY_DEPTH: usize = 2;
const SHALLOW_ENTRY_NAMES: [&str; 4] = ["main", "index", "app", "server"];
const METHOD_KEYWORDS: [&str; 13] = ["if", "for", "while", "switch", "catch", "return", "using", "lock", "foreach", "else", "new", "throw", "await"];

static GENERATED_FILE: LazyLock<Re> = LazyLock::new(|| Re::ci(r"(\.designer\.cs|\.g\.cs|\.g\.i\.cs|\.generated\.[^.]+|\.min\.js|\.min\.css|\.d\.ts)\z"));
static SIGNATURE: LazyLock<Re> = LazyLock::new(|| {
    Re::new(concat!(
        r"(?m)^[ \t]*(?:export[ \t]+|public[ \t]+|private[ \t]+|protected[ \t]+|internal[ \t]+|static[ \t]+|abstract[ \t]+|sealed[ \t]+|partial[ \t]+|default[ \t]+)*",
        r"(?:(?P<type>class|interface|struct|record|enum|trait)[ \t]+(?P<type_name>[A-Za-z_]\w*)",
        r"|(?:async[ \t]+)?(?:function\*?|def|func|fun)[ \t]+(?P<function_name>[A-Za-z_]\w*)[ \t]*[(<]",
        r"|(?:(?:static|async|virtual|override|abstract|sealed|extern|unsafe)[ \t]+)*[\w<>\[\],.?]+[ \t]+(?P<method_name>[A-Za-z_]\w*)[ \t]*\([^;{}]*\)[ \t]*(?:\{|=>|\r?$))"
    ))
});

pub fn find_root(folder: &str) -> String {
    let mut current = nt_abspath(folder);
    loop {
        if Path::new(&current).join(".specs").is_dir() {
            return current;
        }
        let parent = nt_dirname(&current);
        if parent == current {
            return nt_abspath(folder);
        }
        current = parent;
    }
}

fn relative_to(root: &str, path: &str) -> String {
    let (p, r) = (nt_abspath(path), nt_abspath(root));
    let (pl, rl) = (p.to_lowercase(), r.to_lowercase());
    if pl == rl {
        return ".".into();
    }
    match pl.strip_prefix(&format!("{rl}\\")) {
        Some(rest) => p[p.len() - rest.len()..].replace('\\', "/"),
        None => p.replace('\\', "/"),
    }
}

fn is_ignored_file(name: &str) -> bool {
    GENERATED_FILE.is_match(name) || LOCK_FILES.contains(&name.to_lowercase().as_str())
}

fn is_ignored_folder(name: &str) -> bool {
    is_skipped(name) || name == "vendor" || name == "packages" || name.starts_with('.')
}

fn walk_files(folder: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(folder) else { return };
    let (mut dirs, mut names): (Vec<String>, Vec<String>) = (vec![], vec![]);
    for e in entries.flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        if e.path().is_dir() {
            if !is_ignored_folder(&name) {
                dirs.push(name);
            }
        } else {
            names.push(name);
        }
    }
    dirs.sort();
    names.sort();
    for name in names {
        if !is_ignored_file(&name) {
            out.push(folder.join(name));
        }
    }
    for d in dirs {
        walk_files(&folder.join(d), out);
    }
}

/// `(lines, bytes, generated)` of a file; `None` when unreadable.
fn measure_file(path: &Path) -> Option<(i64, i64, bool)> {
    let bytes = std::fs::read(path).ok()?;
    let head = &bytes[..bytes.len().min(HEADER_BYTES)];
    let lowered = String::from_utf8_lossy(head).to_lowercase();
    let generated = lowered.contains("auto-generated") || lowered.contains("autogenerated");
    let lines = bytes.iter().filter(|b| **b == b'\n').count() as i64;
    let last = bytes.last().copied();
    Some((lines + if last.is_some_and(|l| l != b'\n') { 1 } else { 0 }, bytes.len() as i64, generated))
}

fn splitext(lower: &str) -> (&str, &str) {
    match lower.rfind('.') {
        Some(i) if i > 0 && !lower[i..].contains(['/', '\\']) => (&lower[..i], &lower[i..]),
        _ => (lower, ""),
    }
}

fn entry_point_kind(path_from_folder: &str, absolute: &Path) -> Option<&'static str> {
    let normalized = path_from_folder.replace('\\', "/");
    let parts: Vec<&str> = normalized.split('/').collect();
    let name = parts.last().copied().unwrap_or("");
    let lower = name.to_lowercase();
    let (stem, extension) = splitext(&lower);
    if extension == ".sln" || extension == ".slnx" {
        return Some("solution");
    }
    if lower.starts_with("docker-compose") && (extension == ".yml" || extension == ".yaml") {
        return Some("compose");
    }
    if lower == "package.json" {
        let text = std::fs::read(absolute).ok().and_then(|b| String::from_utf8(b).ok())?;
        let package = serde_json::from_str::<Value>(text.strip_prefix('\u{feff}').unwrap_or(&text)).ok()?;
        let truthy = |k: &str| package.get(k).is_some_and(|v| !matches!(v, Value::Null | Value::Bool(false)) && v != &json!("") && v != &json!({}) && v != &json!([]) && v != &json!(0));
        return if package.is_object() && (truthy("main") || truthy("scripts")) { Some("startup") } else { None };
    }
    if !is_code(name) {
        return None;
    }
    if lower == "program.cs" || lower == "startup.cs" {
        return Some("startup");
    }
    if lower.ends_with("controller.cs") || stem.ends_with(".controller") {
        return Some("controller");
    }
    if stem.starts_with("routes") || stem.ends_with(".routes") {
        return Some("route");
    }
    if stem == "index" && parts[..parts.len() - 1].iter().any(|p| p.to_lowercase() == "pages") {
        return Some("page");
    }
    if SHALLOW_ENTRY_NAMES.contains(&stem) && extension != ".css" && extension != ".scss" && parts.len() - 1 <= SHALLOW_ENTRY_DEPTH {
        return Some("startup");
    }
    None
}

/// Up to 5 class or method signatures (names only) of a code file, in file order.
fn signatures_of(path: &Path) -> Vec<String> {
    let Ok(bytes) = std::fs::read(path) else { return vec![] };
    let text = String::from_utf8_lossy(&bytes[..bytes.len().min(HINT_SCAN_BYTES)]).into_owned();
    let mut found: Vec<String> = Vec::new();
    for m in SIGNATURE.find_all(&text) {
        let label = if let Some(type_name) = named(&m, 2) {
            format!("{} {}", named(&m, 1).unwrap_or_default(), type_name)
        } else {
            let name = named(&m, 3).or_else(|| named(&m, 4)).unwrap_or_default();
            if METHOD_KEYWORDS.contains(&name.as_str()) {
                continue;
            }
            format!("{name}(")
        };
        if !found.contains(&label) {
            found.push(label);
        }
        if found.len() >= HINT_LIMIT {
            break;
        }
    }
    found
}

fn named(m: &pycompat::M, index: usize) -> Option<String> {
    m.group(index).filter(|s| !s.is_empty()).map(String::from)
}

fn changed_files(root: &str, folder: &str, changed: &[String]) -> Vec<PathBuf> {
    let mut files: Vec<PathBuf> = Vec::new();
    for item in changed {
        let item = item.trim();
        if item.is_empty() {
            continue;
        }
        let candidates: Vec<PathBuf> = if pycompat::nt_isabs(item) { vec![PathBuf::from(item)] } else { vec![Path::new(root).join(item), Path::new(folder).join(item)] };
        for candidate in candidates {
            if candidate.is_dir() {
                walk_files(&candidate, &mut files);
                break;
            }
            if candidate.is_file() {
                let name = candidate.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
                let rel = relative_to(root, &candidate.display().to_string());
                let parts: Vec<&str> = rel.split('/').collect();
                if !is_ignored_file(&name) && !parts[..parts.len().saturating_sub(1)].iter().any(|p| is_ignored_folder(p)) {
                    files.push(PathBuf::from(nt_abspath(&candidate.display().to_string())));
                }
                break;
            }
        }
    }
    files.sort();
    files.dedup();
    files
}

pub fn build_inventory(folder: &str, root: &str, giant_lines: i64, giant_kb: i64, changed: &[String]) -> Value {
    let (folder, root) = (nt_abspath(folder), nt_abspath(root));
    let files: Vec<PathBuf> = if changed.is_empty() {
        let mut v = Vec::new();
        walk_files(Path::new(&folder), &mut v);
        v
    } else {
        changed_files(&root, &folder, changed)
    };
    let (mut total_files, mut total_lines, mut total_bytes) = (0i64, 0i64, 0i64);
    let mut by_extension: Vec<(String, [i64; 3])> = Vec::new();
    let mut entry_points: Vec<(String, &str)> = Vec::new();
    let mut giants: Vec<(String, i64, i64, Vec<String>)> = Vec::new();
    let giant_bytes = giant_kb * 1024;
    for path in &files {
        let display = path.display().to_string();
        let relative = relative_to(&root, &display);
        let from = if changed.is_empty() { relative_to(&folder, &display) } else { relative.clone() };
        if let Some(kind) = entry_point_kind(&from, path) {
            entry_points.push((relative.clone(), kind));
        }
        let name = path.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        if !is_code(&name) {
            continue;
        }
        let Some((lines, size, generated)) = measure_file(path) else { continue };
        if generated {
            continue;
        }
        total_files += 1;
        total_lines += lines;
        total_bytes += size;
        let extension = splitext(&name.to_lowercase()).1.to_string();
        match by_extension.iter_mut().find(|(e, _)| *e == extension) {
            Some((_, b)) => {
                b[0] += 1;
                b[1] += lines;
                b[2] += size;
            }
            None => by_extension.push((extension, [1, lines, size])),
        }
        if lines > giant_lines || size > giant_bytes {
            giants.push((relative, lines, size, signatures_of(path)));
        }
    }
    giants.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
    by_extension.sort_by(|a, b| a.0.cmp(&b.0));
    entry_points.sort_by(|a, b| a.0.cmp(&b.0));
    let mut ext_map = Map::new();
    for (e, b) in &by_extension {
        ext_map.insert(e.clone(), json!({"files": b[0], "lines": b[1], "bytes": b[2]}));
    }
    let stamp = time::OffsetDateTime::now_local()
        .unwrap_or_else(|_| time::OffsetDateTime::now_utc())
        .format(time::macros::format_description!("[year]-[month]-[day]T[hour]:[minute]:[second]"))
        .unwrap_or_default();
    json!({
        "folder": if folder.to_lowercase() != root.to_lowercase() { relative_to(&root, &folder) } else { ".".to_string() },
        "generated_at": stamp,
        "totals": {"files": total_files, "lines": total_lines, "bytes": total_bytes},
        "by_extension": Value::Object(ext_map),
        "entry_points": entry_points.iter().map(|(p, k)| json!({"path": p, "kind": k})).collect::<Vec<_>>(),
        "giant": giants.iter().map(|(p, l, b, h)| json!({"path": p, "lines": l, "bytes": b, "hint": h})).collect::<Vec<_>>(),
        "thresholds": {"lines": giant_lines, "kb": giant_kb, "bytes": giant_bytes},
    })
}

pub fn default_name(folder: &str, root: &str) -> String {
    if nt_abspath(folder).to_lowercase() == nt_abspath(root).to_lowercase() {
        return ROOT_NAME.into();
    }
    relative_to(root, &nt_abspath(folder)).replace('/', "-")
}

pub fn inventory_path(root: &str, name: &str) -> PathBuf {
    let mut path = PathBuf::from(root);
    for part in [".specs", "project", "loop", "internal", "inventory"] {
        path.push(part);
    }
    path.join(format!("{name}.json"))
}

pub fn write_atomically(path: &Path, document: &Value) -> std::io::Result<()> {
    let mut text = py_json_dumps_indent(document, false, 2);
    text.push('\n');
    crate::loop_io::atomic_write_text(path, &text)
}



pub fn run_cli(args: &[String]) -> (i32, String, String) {
    let mut folder: Option<String> = None;
    let (mut json_out, mut no_write) = (false, false);
    let (mut giant_lines, mut giant_kb) = (DEFAULT_GIANT_LINES, DEFAULT_GIANT_KB);
    let (mut changed, mut root_opt, mut name_opt, mut out_opt) = (String::new(), None::<String>, None::<String>, None::<String>);
    let mut index = 0;
    while index < args.len() {
        let value = |i: usize| args.get(i + 1).cloned();
        match args[index].as_str() {
            "--json" => index += 1,
            "--no-write" => {
                no_write = true;
                index += 1;
            }
            flag @ ("--giant-lines" | "--giant-kb") if value(index).is_some() => {
                match value(index).and_then(|v| v.parse::<i64>().ok()) {
                    Some(n) => {
                        if flag == "--giant-lines" { giant_lines = n } else { giant_kb = n }
                    }
                    None => return (2, String::new(), format!("code_inventory: error: argument {flag}: invalid int value: {}\n", pycompat::py_repr_str(&value(index).unwrap_or_default()))),
                }
                index += 2;
            }
            "--changed" if value(index).is_some() => {
                changed = value(index).unwrap_or_default();
                index += 2;
            }
            "--root" if value(index).is_some() => {
                root_opt = value(index);
                index += 2;
            }
            "--name" if value(index).is_some() => {
                name_opt = value(index);
                index += 2;
            }
            "--out" if value(index).is_some() => {
                out_opt = value(index);
                index += 2;
            }
            other => {
                if folder.is_none() {
                    folder = Some(other.to_string());
                }
                index += 1;
            }
        }
    }
    json_out |= args.iter().any(|a| a == "--json");
    let Some(folder) = folder else {
        return (2, String::new(), "usage: code_inventory [-h] [--json] [--giant-lines GIANT_LINES] [--giant-kb GIANT_KB] [--changed CHANGED] [--root ROOT] [--name NAME] [--out OUT] [--no-write] folder\ncode_inventory: error: the following arguments are required: folder\n".into());
    };
    let folder = nt_abspath(&folder);
    if !Path::new(&folder).is_dir() {
        return (2, String::new(), format!("not a folder: {folder}\n"));
    }
    let root = root_opt.map(|r| nt_abspath(&r)).unwrap_or_else(|| find_root(&folder));
    let changed_list: Vec<String> = changed.split(',').filter(|c| !c.trim().is_empty()).map(String::from).collect();
    let document = build_inventory(&folder, &root, giant_lines, giant_kb, &changed_list);
    let mut target: Option<PathBuf> = None;
    if !no_write {
        if let Some(out) = out_opt.filter(|o| !o.is_empty()) {
            target = Some(PathBuf::from(nt_abspath(&out)));
        } else if changed_list.is_empty() && Path::new(&root).join(".specs").is_dir() {
            target = Some(inventory_path(&root, &name_opt.unwrap_or_else(|| default_name(&folder, &root))));
        }
    }
    let mut written = String::new();
    let mut stderr = String::new();
    if let Some(t) = &target {
        match write_atomically(t, &document) {
            Ok(()) => written = t.display().to_string(),
            Err(error) => stderr.push_str(&format!("could not write {}: {error}\n", t.display())),
        }
    }
    if json_out {
        return (0, format!("{}\n", py_json_dumps_indent(&document, false, 2)), stderr);
    }
    let totals = &document["totals"];
    let giant = document["giant"].as_array().cloned().unwrap_or_default();
    let mut out = format!(
        "inventory: {} files, {} giant ({} lines, {} KB)\n",
        totals["files"],
        giant.len(),
        totals["lines"],
        totals["bytes"].as_i64().unwrap_or(0) / 1024
    );
    for item in &giant {
        let hints: Vec<&str> = item["hint"].as_array().map(|a| a.iter().filter_map(Value::as_str).collect()).unwrap_or_default();
        out.push_str(&format!(
            "  giant: {} ({} lines, {} KB) {}\n",
            item["path"].as_str().unwrap_or(""),
            item["lines"],
            item["bytes"].as_i64().unwrap_or(0) / 1024,
            hints.join(", ")
        ));
    }
    out.push_str(&format!("  entry points: {}\n", document["entry_points"].as_array().map_or(0, Vec::len)));
    if !written.is_empty() {
        out.push_str(&format!("  written: {written}\n"));
    }
    (0, out, stderr)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn measures_code_flags_giants_and_entry_points() {
        let dir = tempfile::tempdir().unwrap();
        let big: String = (0..30).map(|i| format!("function f{i}() {{}}\n")).collect();
        for (rel, text) in [
            ("src/main.ts", "export function start() {}\n"),
            ("src/Big.ts", big.as_str()),
            ("src/Program.cs", "class Program {}\n"),
            ("api/UsersController.cs", "public class UsersController {}\n"),
            ("src/x.designer.cs", "x"),
            ("node_modules/a/b.js", "ignored"),
            ("MyApp.sln", ""),
            ("package.json", "{\"scripts\": {\"test\": \"x\"}}"),
        ] {
            let p = dir.path().join(rel);
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(p, text).unwrap();
        }
        let doc = build_inventory(&dir.path().display().to_string(), &dir.path().display().to_string(), 20, 200, &[]);
        assert_eq!(doc["totals"]["files"], 4);
        assert_eq!(doc["giant"][0]["path"], "src/Big.ts");
        assert_eq!(doc["giant"][0]["hint"][0], "f0(");
        let kinds: Vec<(&str, &str)> = doc["entry_points"].as_array().unwrap().iter().map(|e| (e["path"].as_str().unwrap(), e["kind"].as_str().unwrap())).collect();
        assert!(kinds.contains(&("MyApp.sln", "solution")) && kinds.contains(&("api/UsersController.cs", "controller")) && kinds.contains(&("src/main.ts", "startup")) && kinds.contains(&("package.json", "startup")));
    }
}
